async function seed() {
  console.log("Inserindo efetivo oficial de 12/11/2026...");
  
  // 1. Atualiza/insere no daily_reports
  const { data: existingRows } = await adminClient
    .from("daily_reports")
    .select("id, shift, recursos, incendios, outras, notes")
    .eq("report_date", "2026-11-12");

  const shifts = ["noturno", "parcial"];
  for (const shift of shifts) {
    const existing = existingRows?.find((r) => r.shift === shift);
    if (existing) {
      const { error } = await adminClient
        .from("daily_reports")
        .update({
          efetivo: EFETIVO_12_11,
          updated_at: new Date().toISOString(),
        })
        .eq("id", existing.id);
      if (error) console.error(`Erro ao atualizar shift ${shift}:`, error);
      else console.log(`Shift ${shift} atualizado com sucesso!`);
    } else {
      const { error } = await adminClient
        .from("daily_reports")
        .insert({
          report_date: "2026-11-12",
          shift,
          efetivo: EFETIVO_12_11,
          recursos: existingRows?.[0]?.recursos || [],
          incendios: existingRows?.[0]?.incendios || [],
          outras: existingRows?.[0]?.outras || [],
          notes: existingRows?.[0]?.notes || "{}",
          updated_at: new Date().toISOString(),
        });
      if (error) console.error(`Erro ao inserir shift ${shift}:`, error);
      else console.log(`Shift ${shift} inserido com sucesso!`);
    }
  }

  // 2. Atualiza o report_data (ID 1) se existir para manter fallback sempre atualizado
  const { data: rd } = await adminClient.from("report_data").select("id, data").eq("id", 1).maybeSingle();
  if (rd?.data) {
    const updatedData = { ...rd.data, efetivo: EFETIVO_12_11 };
    await adminClient.from("report_data").update({ data: updatedData }).eq("id", 1);
    console.log("report_data (ID 1) sincronizado com o efetivo de 12/11/2026!");
  }

  console.log("Concluído!");
}

seed();

